const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'node_modules/@yiminlab/voyage');
const {version} = JSON.parse(fs.readFileSync(path.join(source, 'package.json'), 'utf8'));
const license = fs.readFileSync(path.join(source, 'LICENSE'), 'utf8').trim();
const content = `/* @yiminlab/voyage ${version} — generated by npm run vendor:voyage\n${license}\n*/\n` +
  ['tokens.css', 'voyage.css'].map(file => fs.readFileSync(path.join(source, file), 'utf8')).join('\n');
const target = path.join(root, 'src/ablation_workbench/web/voyage.css');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== content) throw Error('Run npm run vendor:voyage to synchronize the bundled styles');
} else {
  fs.writeFileSync(target, content);
}
