const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');

const root = path.resolve(__dirname, '..');
for (const entry of ['theme.js', 'voyage-toolbar.jsx', 'messages.jsx']) {
  const output = path.join(root, 'src/ablation_workbench/web', entry.replace('.jsx', '.js'));
  const result = esbuild.buildSync({
    entryPoints:[path.join(root, 'ui', entry)], outfile:output, bundle:true, write:false,
    format:'iife', jsx:'automatic', target:'es2022', minify:true, legalComments:'inline',
    define:{'process.env.NODE_ENV':'"production"'}, logLevel:'error',
    banner:{js:'/* Generated by npm run build:ui; edit ui/ sources. */'},
  }).outputFiles;
  for (const file of result) {
    if (process.argv.includes('--check')) {
      if (!fs.readFileSync(file.path).equals(Buffer.from(file.contents))) throw Error('Run npm run build:ui to synchronize the bundled UI');
    } else {
      fs.writeFileSync(file.path, file.contents);
    }
  }
}
